// Generates packages/core/src/db/migrations.generated.ts from packages/core/migrations/*.sql
// so that both Vite (desktop) and Node (MCP, tests, seed) can load the SQL without loaders.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "packages/core/migrations");
const out = join(root, "packages/core/src/db/migrations.generated.ts");

const files = readdirSync(dir)
  .filter((f) => /^\d{4}_.+\.sql$/.test(f))
  .sort();
const entries = files.map((f) => ({
  version: Number(f.slice(0, 4)),
  name: f,
  sql: readFileSync(join(dir, f), "utf8"),
}));
const content =
  "// AUTO-GENERATED by scripts/gen-migrations.mjs. Do not edit.\n" +
  "export interface Migration { version: number; name: string; sql: string }\n" +
  "export const migrations: Migration[] = " +
  JSON.stringify(entries, null, 2) +
  ";\n";

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== content) {
    console.error("migrations.generated.ts is out of date. Run: pnpm gen:migrations");
    process.exit(1);
  }
  const spec = readFileSync(join(root, "docs/spec/schema.sql"), "utf8");
  if (entries[0]?.sql !== spec) {
    console.error("0001_init.sql must be identical to docs/spec/schema.sql");
    process.exit(1);
  }
} else {
  writeFileSync(out, content);
  console.log(`Wrote ${files.length} migration(s) to ${out}`);
}
